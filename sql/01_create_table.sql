  snapshot_ts string,
  trip_id string,
  route_id string,
  route_short_name string,
  route_type int,
  headsign string,
  stop_id string,
  stop_name string,
  stop_sequence int,
  arrival_delay_s int,
  departure_delay_s int,
  hour_local int,
  temperature_2m double,
  precipitation double,
  direction_id int,
  service_date string,
  day_of_week int,
  day_type string,
  is_school_break boolean,
  special_day string,
  season string,
  arrival_hour_local int,
  is_dark boolean,
  stop_lat double,
  stop_lon double,
  dist_center_km double,
  zone string,
  bank string,
  crosses_danube boolean,
  on_bus_lane boolean,
  near_signal boolean,
  signals_within_300m int,
  near_mall boolean,
  trip_length_m double,
  stops_in_trip int,
  position_ratio double,
  segment_length_m double,
  prev_stop_id string,
  prev_stop_name string,
  origin_delay_s int,
  delay_increment_s int,
  prediction_lead_s int,
  sched_headway_s int,
  actual_headway_s int,
  bunched boolean,
  rain double,
  snowfall double,
  snow_depth double,
  wind_speed_10m double,
  wind_gusts_10m double,
  visibility double,
  weather_code int,
  alert_category string,
  alert_duration string,
  alert_stop_change boolean,
  segment_speed_kmh double,
  segment_speed_obs int,
  vehicle_id string,
  prev_trip_end_delay_s int,
  quality_flag string,
  reliable boolean,
  sched_layover_s int
)
PARTITIONED BY (dt string)
STORED AS PARQUET
LOCATION 's3://BUCKET/curated/delays/'
TBLPROPERTIES (
  'projection.enabled' = 'true',
  'projection.dt.type' = 'date',
  'projection.dt.format' = 'yyyy-MM-dd',
  'projection.dt.range' = '2026-10-29,NOW',
  'storage.location.template' = 's3://BUCKET/curated/delays/dt=${dt}'
);
